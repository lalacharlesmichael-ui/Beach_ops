begin;

do $$
begin
  create type public.staff_role as enum ('Admin', 'Staff', 'Kitchen');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.staff_status as enum ('Active', 'Inactive');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.table_status as enum ('Available', 'Occupied', 'For Cleaning');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.prep_station as enum ('Kitchen', 'Bar');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.order_status as enum (
    'Awaiting Payment',
    'Paid',
    'Preparing',
    'Ready',
    'Served',
    'Cancelled',
    'Refunded'
  );
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.payment_status as enum ('Pending', 'Paid', 'Failed', 'Refunded');
exception
  when duplicate_object then null;
end $$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.staff_accounts (
  id text primary key,
  name text not null check (length(trim(name)) > 0),
  username text not null unique check (username = lower(username)),
  password text not null check (length(password) > 0),
  role public.staff_role not null default 'Staff',
  status public.staff_status not null default 'Active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on column public.staff_accounts.password is
  'Temporary demo-login password field. Replace with Supabase Auth or password hashes before production.';

create table if not exists public.tables (
  id text primary key,
  name text not null check (length(trim(name)) > 0),
  area text not null check (length(trim(area)) > 0),
  capacity integer not null check (capacity > 0),
  status public.table_status not null default 'Available',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.table_sessions (
  id text primary key,
  table_id text not null references public.tables(id) on update cascade on delete restrict,
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (closed_at is null or closed_at >= opened_at)
);

create table if not exists public.menu_items (
  id text primary key,
  name text not null check (length(trim(name)) > 0),
  category text not null check (length(trim(category)) > 0),
  price_cents integer not null check (price_cents >= 0),
  station public.prep_station not null,
  available boolean not null default true,
  stock_qty integer not null default 0 check (stock_qty >= 0),
  archived boolean not null default false,
  tone text not null default 'sunset',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  session_id text not null references public.table_sessions(id) on update cascade on delete restrict,
  table_id text not null references public.tables(id) on update cascade on delete restrict,
  status public.order_status not null default 'Awaiting Payment',
  payment_status public.payment_status not null default 'Pending',
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  paid_by text,
  staff text not null,
  customer_name text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on update cascade on delete cascade,
  line_id text not null,
  menu_item_id text not null references public.menu_items(id) on update cascade on delete restrict,
  name text not null,
  category text not null,
  station public.prep_station not null,
  quantity integer not null check (quantity > 0),
  price_cents integer not null check (price_cents >= 0),
  instructions text not null default '',
  created_at timestamptz not null default now(),
  unique (order_id, line_id)
);

create table if not exists public.payments (
  id text primary key,
  order_id text not null references public.orders(id) on update cascade on delete restrict,
  method text not null default 'Cash',
  status public.payment_status not null default 'Paid',
  amount_cents integer not null check (amount_cents >= 0),
  amount_received_cents integer not null check (amount_received_cents >= amount_cents),
  change_cents integer not null check (change_cents >= 0),
  customer_name text not null,
  staff text not null,
  paid_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id text primary key,
  category text not null check (length(trim(category)) > 0),
  description text not null check (length(trim(description)) > 0),
  amount_cents integer not null check (amount_cents > 0),
  staff text not null,
  spent_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id text primary key,
  actor text not null,
  action text not null,
  detail text not null,
  logged_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  id text primary key default 'default',
  print_receipts boolean not null default true,
  sound_alerts boolean not null default true,
  require_served_before_cleaning boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.settings (id)
values ('default')
on conflict (id) do nothing;

