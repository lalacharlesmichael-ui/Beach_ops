do $$
declare
  app_table text;
begin
  foreach app_table in array array[
    'staff_accounts',
    'tables',
    'table_sessions',
    'menu_items',
    'orders',
    'order_items',
    'payments',
    'expenses',
    'audit_logs',
    'settings'
  ]
  loop
    execute format('alter table public.%I enable row level security', app_table);
    execute format('drop policy if exists "Allow app CRUD" on public.%I', app_table);
    execute format(
      'create policy "Allow app CRUD" on public.%I for all to anon, authenticated using (true) with check (true)',
      app_table
    );
  end loop;
end $$;

commit;
